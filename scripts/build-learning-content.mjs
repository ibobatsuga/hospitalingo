import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "content", "HOSPITALITY-MASTER.md");
const outputPath = path.join(root, "lib", "generated-glossary.ts");

const markdown = await readFile(sourcePath, "utf8");
const blocks = markdown.split(/(?=^<a id="term-)/gm).filter((block) => /^<a id="term-/.test(block));

function clean(value = "") {
  return value
    .replace(/<!--.*?-->/gs, " ")
    .replace(/\*\*/g, "")
    .replace(/`/g, "")
    .replace(/\[(.*?)\]\(.*?\)/g, "$1")
    .replace(/^[-*]\s+/gm, "")
    .replace(/^>\s?/gm, "")
    .replace(/\s+/g, " ")
    .trim();
}

function section(block, name) {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = block.match(new RegExp(`^### ${escaped}\\s*\\n([\\s\\S]*?)(?=^### |^---$|\\Z)`, "m"));
  return clean(match?.[1]);
}

function compact(value, maximum = 220) {
  if (!value) return "";
  const paragraphs = value.split(/(?<=[.!?])\s+(?=[A-ZÀ-Ý0-9])/).filter(Boolean);
  const selected = paragraphs.slice(0, 2).join(" ");
  if (selected.length <= maximum) return selected;
  const shortened = selected.slice(0, maximum).replace(/\s+\S*$/, "").trim();
  return `${shortened}…`;
}

function slug(value) {
  return value
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 64);
}

const seen = new Map();
const terms = blocks.map((block, index) => {
  const heading = block.match(/^## (\d{1,3})\. (.+)$/m);
  if (!heading) throw new Error(`Entry ${index + 1} has no heading.`);
  const sourceNumber = Number(heading[1]);
  const term = clean(heading[2]);
  const department = clean(block.match(/^- \*\*Department:\*\* (.+)$/m)?.[1] ?? "Hospitality Operations");
  const subcategory = clean(block.match(/^- \*\*Subcategory:\*\* (.+)$/m)?.[1] ?? "Operations");
  const sourcePage = Number(block.match(/^- \*\*Source PDF page:\*\* (\d+)$/m)?.[1] ?? 0);
  const baseId = slug(term) || `term-${index + 1}`;
  const occurrence = (seen.get(baseId) ?? 0) + 1;
  seen.set(baseId, occurrence);
  const id = occurrence === 1 ? baseId : `${baseId}-${occurrence}`;
  const meaning = compact(section(block, "Pengertian"));
  const workplaceUse = compact(section(block, "Peran dan Fungsi") || section(block, "Intisari"));
  const controlNote = compact(section(block, "Tindakan Pengendalian"), 160);
  const isRestaurant = /F&B|FOOD|BANQUET|KITCHEN|RESTAURANT/i.test(`${department} ${subcategory} ${term}`);

  return {
    id,
    sourceNumber,
    term,
    department,
    subcategory,
    domain: isRestaurant ? "restaurant" : "hotel",
    meaning,
    workplaceUse,
    controlNote,
    sourcePage,
  };
});

if (terms.length !== 436) throw new Error(`Expected 436 terms, found ${terms.length}.`);

const banner = `// Generated by scripts/build-learning-content.mjs from content/HOSPITALITY-MASTER.md.\n// Do not edit this file manually; update the Markdown source and rerun the generator.\n`;
await writeFile(
  outputPath,
  `${banner}export const generatedGlossary = ${JSON.stringify(terms, null, 2)} as const;\n`,
  "utf8",
);

console.log(`Generated ${terms.length} compact glossary entries at ${path.relative(root, outputPath)}.`);
